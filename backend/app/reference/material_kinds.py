"""Виды номенклатуры 1С — порядок групп в дефиците материалов."""

KIND_ORDER = [
    "Печатные материалы для производства",
    "Упаковочные материалы для производства",
    "Тара для производства (учет себестоимости по сер)",
    "Тара (без серий)",
    "Вспомогательные материалы для производства",
    "Сырье",
    "Продукты переработки",
    "Нерасфасованные продукты КЛС",
    "Материалы для лабораторий",
    "Химия бытовая и техническая",
]


def kind_rank(kind: str | None) -> int:
    return KIND_ORDER.index(kind) if kind in KIND_ORDER else len(KIND_ORDER)
